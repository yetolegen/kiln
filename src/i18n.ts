export function hintText(hint: Hint): string {
  const p = hint.params;
  const hand = p.side === 'left' ? 'левой' : p.side === 'right' ? 'правой' : 'отмеченной';
  switch (hint.id) {
    case 'tear': return 'Слишком быстро на отмеченном участке — веди руки медленнее, держи их у стенок';
    case 'wobble': return `Смести обе руки ${p.dir === 'right' ? 'вправо' : 'влево'} — середина между ними должна совпасть с осью круга`;
    case 'tooThin': return 'Стенка слишком тонкая. Поддерживайте её одной рукой, другую держите горизонтально над краем, затем медленно опускайте.';
    case 'collapse':
      if (p.cause === 'bottomHole') return 'Вы продавили дно насквозь. Нажмите «Начать сначала». В новом сосуде вдавливайте большой палец только на глубину одной фаланги.';
      if (p.cause === 'wallTorn') return 'Стенка разорвалась от долгого растягивания. Нажмите «Начать сначала». Отпускайте щипок, когда отверстие достигло нужной ширины.';
      if (p.cause === 'pancake') return 'Сосуд сплющен в лепёшку. Нажмите «Начать сначала». Прекращайте давление, когда край достиг нужной высоты.';
      return 'Сосуд осел. Поддерживайте стенку одной рукой. Другую держите горизонтально над краем полсекунды, затем медленно опускайте для восстановления.';
    case 'thinFloor': return 'Палец вошёл слишком глубоко: дно истончается. Остановите надавливание и поднимите большой палец, иначе появится сквозное отверстие.';
    case 'overStretch': return 'Вы растягиваете отверстие слишком долго. Отпустите щипок сейчас: стенка истончается и скоро разорвётся.';
    case 'tooFlat': return 'Сосуд стал слишком низким. Прекратите давление и уберите ладонь от края, иначе глина превратится в лепёшку.';
    case 'overhang': return 'На отмеченном участке стенка слишком резко расширяется — сузь его или расширь участок ниже';
    case 'handsTooFar': return `Поднеси ${p.side === 'left' ? 'левую руку к левой' : p.side === 'right' ? 'правую руку к правой' : 'отмеченную руку к её'} стенке`;
    case 'oneHand': return 'Не вижу вторую руку — разведи кисти, чтобы камера видела обе';
    case 'noHands': return 'Покажи обе руки камере';
    case 'trackingUncertain':
      if (p.interrupted === 'true') return p.status === 'reacquiring' ? 'Снова находим руки. Глина на паузе — задержите кисти в кадре.' : p.status === 'oneHand' ? 'Не вижу опорную руку. Верните её к стенке сосуда — глина на паузе.' : 'Отслеживание потеряно. Верните руки в кадр и разведите кисти. Глина на паузе.';
      return 'Не могу уверенно распознать руки — разведи кисти и держи их в освещённой части кадра';
    case 'targetMismatch':
      if (p.cause === 'tooWide') return 'На отмеченной высоте сосуд шире образца — сведи руки';
      if (p.cause === 'tooNarrow') return 'На отмеченной высоте сосуд уже образца — разведи руки шире';
      if (p.cause === 'tooHigh') return 'Сосуд выше образца. Поддерживайте стенку, держите другую ладонь горизонтально над краем полсекунды и медленно опускайте.';
      return 'Сосуд ниже образца. Поддерживайте стенку, держите другую ладонь горизонтально у основания три секунды и медленно поднимайте.';
    case 'pinchLoose': return `Сведи большой и указательный пальцы плотнее на ${hand} руке`;
    case 'noSupport': return `Держите ладонь ${hand} руки у боковой стенки для поддержки.`;
    case 'holdStill': return `Не двигайте рабочую руку. До активации: ${Number(p.remainingS ?? 0).toFixed(1)} с. Другой рукой поддерживайте стенку.`;
    case 'liftTooFast': return 'Поднимайте руку медленнее. Снова задержите её горизонтально у основания на три секунды.';
    case 'notHorizontal': return `Раскройте ${hand === 'левой' ? 'левую' : hand === 'правой' ? 'правую' : 'отмеченную'} ладонь и поверните кисть горизонтально — пальцы в сторону.`;
    case 'thumbNotOnTop': return `Направьте большой палец вниз и подведите его к центру верхней поверхности${p.dx === 'left' ? ' — левее' : p.dx === 'right' ? ' — правее' : ''}${p.dy === 'up' ? ', выше' : p.dy === 'down' ? ', ниже' : ''}. Затем слегка надавите вниз.`;
    case 'noIndentation': return 'Сначала сделайте неглубокую ямку большим пальцем вниз, поддерживая стенку другой рукой.';
    case 'pinchFirst': return `Сначала соедините большой и указательный пальцы ${hand} руки внутри ямки. Задержите щипок, затем медленно разводите пальцы.`;
    case 'indentTooFast': return 'Давите большим пальцем медленнее. Снова коснитесь центра сверху и плавно нажмите.';
    case 'compressTooFast': return 'Опускайте ладонь медленнее. Снова задержите её горизонтально над краем полсекунды.';
    case 'spreadTooFast': return 'Разводите пальцы медленнее. Снова начните с сомкнутого щипка внутри ямки.';
    case 'rimPlacement': return p.dir === 'lower' ? 'Опустите горизонтальную ладонь чуть выше края. Другой рукой поддерживайте стенку.' : 'Подведите горизонтальную ладонь ближе к центру над краем. Другой рукой поддерживайте стенку.';
    case 'handsTooLow': return 'Подними обе открытые ладони выше сосуда и удерживай';
    case 'handsUneven': return `Подними ${p.raise === 'left' ? 'левую' : 'правую'} руку — кисти должны быть на одной высоте`;
    case 'handsNotOpposite': return 'Размести руки по разные стороны сосуда';
    case 'notMoving': return typeof p.instruction === 'string' ? p.instruction : 'Активация завершена. Медленно ведите рабочую ладонь: от основания вверх для подъёма или от края вниз для уплотнения. Опорная рука остаётся у стенки.';
    case 'offWheel': return 'Поднеси руки к стенкам сосуда на одной высоте';
    case 'atLimit': return 'Сосуд уже достиг предельной высоты — попробуй изменить его ширину';
    case 'recovered': return 'Сосуд восстановлен. Можно снова формовать';
  }
}
